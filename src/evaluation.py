"""Deterministic evaluation and benchmarking suite for LLM-generated analytical explanations.
Evaluates factual consistency, numerical accuracy, hallucination detection, latency, and throughput.
"""

from typing import Dict, List, Any, Optional
import re
import pandas as pd
import numpy as np


def extract_numbers_from_text(text: str) -> List[float]:
    """Extract all numerical values (integers and floats) from text."""
    pattern = r"[-+]?\b\d+(?:\.\d+)?\b"
    matches = re.findall(pattern, text)
    return [float(m) for m in matches]


def _extract_feature_context(text: str, feature_name: str) -> str:
    """Extract sentences or clauses mentioning the specified feature."""
    clauses = re.split(r'[\.\n\r;]|(?:\bwhile\b|\bwhereas\b|\bbut\b|\bin contrast\b)', text, flags=re.IGNORECASE)
    variants = [feature_name.lower(), feature_name.lower().replace("_", " ")]
    matched = [c.strip() for c in clauses if any(v in c.lower() for v in variants)]
    if matched:
        return " ".join(matched)
    # Fallback to local window if regex split fails
    pos = text.lower().find(feature_name.lower())
    if pos != -1:
        start = max(0, pos - 80)
        end = min(len(text), pos + 80)
        return text[start:end]
    return text


def evaluate_factual_consistency(
    explanation_text: str,
    top_features: Optional[List[str]] = None,
    expected_directions: Optional[Dict[str, str]] = None,
    task: str = "customer_explanation"
) -> Dict[str, Any]:
    """Deterministically check if LLM response correctly mentions key facts for the specific task.

    Parameters
    ----------
    explanation_text : str
        Text generated by the LLM.
    top_features : List[str], optional
        For customer_explanation: features expected to be identified as influential.
    expected_directions : Dict[str, str], optional
        For customer_explanation: expected direction of influence ('positive'/'negative').
    task : str, optional
        Analytical task: 'customer_explanation' or 'model_comparison'. Default is 'customer_explanation'.

    Returns
    -------
    Dict[str, Any]
        Dictionary with task-specific verification metrics and factual consistency score (0-1.0).
    """
    text_lower = explanation_text.lower()

    if task == "model_comparison":
        expected_models = ["XGBoost", "Linear Regression", "Random Forest"]
        cited_models = [m for m in expected_models if m.lower() in text_lower]
        model_coverage = len(cited_models) / len(expected_models)

        # Check whether XGBoost is correctly identified as superior / best performing
        rf_hallucination = bool(re.search(r"random\s+forest[^\.]*?(?:best|top|superior|lowest|winner)", text_lower))
        linear_hallucination = bool(re.search(r"linear\s+regression[^\.]*?(?:best|top|superior|lowest|winner)", text_lower))
        xgb_winner = bool(re.search(r"xgboost[^\.]*?(?:best|top|superior|lowest|winner|outperform|most\s+accurate)", text_lower))
        correct_winner = xgb_winner and not rf_hallucination and not linear_hallucination

        has_metrics_context = ("mae" in text_lower or "mean absolute error" in text_lower) and ("r2" in text_lower or "r²" in text_lower or "rmse" in text_lower)
        metric_score = 1.0 if has_metrics_context else 0.5
        winner_score = 1.0 if correct_winner else 0.0

        factual_score = round(0.4 * model_coverage + 0.4 * winner_score + 0.2 * metric_score, 3)

        return {
            "task": "model_comparison",
            "cited_models": cited_models,
            "model_coverage": round(model_coverage, 2),
            "correct_winner_identified": correct_winner,
            "factual_consistency_score": factual_score
        }

    # Default: customer_explanation
    if top_features is None:
        top_features = ["Payment_Ratio", "Credit_Utilization"]
    if expected_directions is None:
        expected_directions = {
            "Payment_Ratio": "positive",
            "Credit_Utilization": "negative"
        }

    cited_features = []
    direction_checks = {}

    positive_keywords = ["increas", "improv", "boost", "benefit", "positive", "gain", "uplift", "raise", "higher score", "higher credit score"]
    negative_keywords = ["decreas", "reduc", "hurt", "penalty", "negative", "risk", "detract", "drop", "lowers", "lowering", "lower score", "lower credit score", "downward"]

    for feat in top_features:
        feat_name_variants = [feat.lower(), feat.lower().replace("_", " ")]
        is_cited = any(v in text_lower for v in feat_name_variants)
        if is_cited:
            cited_features.append(feat)

        expected_dir = expected_directions.get(feat, "")
        if is_cited and expected_dir:
            feat_context = _extract_feature_context(text_lower, feat)
            has_pos = any(w in feat_context for w in positive_keywords)
            has_neg = any(w in feat_context for w in negative_keywords)

            if expected_dir == "positive":
                has_correct_dir = has_pos and not has_neg
            else:
                has_correct_dir = has_neg and not has_pos

            direction_checks[feat] = bool(has_correct_dir)

    citation_ratio = len(cited_features) / len(top_features) if top_features else 1.0
    direction_ratio = (
        sum(1 for v in direction_checks.values() if v) / len(direction_checks)
        if direction_checks else 0.0
    )
    overall_factual_score = round(0.5 * citation_ratio + 0.5 * direction_ratio, 3)

    return {
        "task": "customer_explanation",
        "cited_features": cited_features,
        "citation_ratio": round(citation_ratio, 2),
        "direction_checks": direction_checks,
        "factual_consistency_score": overall_factual_score
    }


def evaluate_numerical_accuracy(
    explanation_text: str,
    expected_numbers: List[float],
    tolerance: float = 0.05
) -> Dict[str, Any]:
    """Verify whether numbers cited in the explanation match the supplied analytical evidence.

    Parameters
    ----------
    explanation_text : str
        Generated explanation.
    expected_numbers : List[float]
        Ground-truth numbers from model/metrics (e.g. [645.0, 9.93, 0.967]).
    tolerance : float
        Acceptable relative error threshold (default 5%).

    Returns
    -------
    Dict[str, Any]
        Dictionary of matched numbers, matched ratio, and score.
    """
    extracted = extract_numbers_from_text(explanation_text)
    if not extracted:
        # No numbers mentioned
        return {
            "extracted_count": 0,
            "matched_count": 0,
            "accuracy_score": 0.5,  # neutral score when qualitative
            "note": "No numerical values cited"
        }

    matched = []
    matched_indices = set()
    for exp_num in expected_numbers:
        for idx, found_num in enumerate(extracted):
            if idx in matched_indices:
                continue
            abs_diff = abs(found_num - exp_num)
            rel_diff = abs_diff / (abs(exp_num) + 1e-6)
            is_match = False
            if abs(exp_num) >= 5.0:
                is_match = (rel_diff <= tolerance) or (abs_diff <= 1.0)
            else:
                is_match = (rel_diff <= tolerance) or (abs_diff <= 0.02)
            if is_match:
                matched.append({"expected": exp_num, "found": found_num})
                matched_indices.add(idx)
                break

    matched_ratio = len(matched) / len(expected_numbers) if expected_numbers else 1.0
    return {
        "extracted_numbers": extracted,
        "matched_numbers": matched,
        "matched_count": len(matched),
        "accuracy_score": round(min(1.0, matched_ratio), 3)
    }


def evaluate_response_quality(
    explanation_text: str,
    expected_numbers: Optional[List[float]] = None,
    top_features: Optional[List[str]] = None,
    task: str = "customer_explanation"
) -> Dict[str, Any]:
    """Comprehensive composite evaluation of an LLM analytical explanation.

    Parameters
    ----------
    explanation_text : str
        Generated explanation text.
    expected_numbers : List[float], optional
        Expected numerical anchors (e.g., predicted credit score, R2).
    top_features : List[str], optional
        Expected feature names for customer explanation.
    task : str, optional
        'customer_explanation' or 'model_comparison'. Default is 'customer_explanation'.

    Returns
    -------
    Dict[str, Any]
        Full evaluation report with component scores and overall quality rating.
    """
    if expected_numbers is None:
        expected_numbers = []

    factual_eval = evaluate_factual_consistency(explanation_text, top_features=top_features, task=task)
    numeric_eval = evaluate_numerical_accuracy(explanation_text, expected_numbers=expected_numbers)

    # Word count and completeness check
    word_count = len(explanation_text.split())
    is_adequate_length = 30 <= word_count <= 400

    # Composite score (Factual: 50%, Numerical: 30%, Completeness: 20%)
    factual_score = factual_eval["factual_consistency_score"]
    numeric_score = numeric_eval["accuracy_score"]
    length_score = 1.0 if is_adequate_length else 0.5

    composite_score = round(
        0.5 * factual_score + 0.3 * numeric_score + 0.2 * length_score,
        3
    )

    return {
        "word_count": word_count,
        "factual_consistency": factual_eval,
        "numerical_accuracy": numeric_eval,
        "composite_quality_score": composite_score,
        "rating": "High" if composite_score >= 0.8 else ("Moderate" if composite_score >= 0.5 else "Low")
    }
